import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const distDirectory = path.join(projectRoot, "dist");
const appSource = fs.readFileSync(path.join(distDirectory, "app.js"), "utf8");
const imageBlock = appSource.match(/const MEMBER_IMAGES = \{([\s\S]*?)\n\};/);

if (!imageBlock) throw new Error("Unable to find MEMBER_IMAGES in dist/app.js");

const avatarData = {};
const entryPattern = /"([^"]+)":\s*"([^"]+)"/g;
let match;

while ((match = entryPattern.exec(imageBlock[1]))) {
  const [, memberName, relativeSource] = match;
  const imagePath = path.resolve(distDirectory, relativeSource);
  const extension = path.extname(imagePath).toLowerCase();
  const mimeType = extension === ".jpg" || extension === ".jpeg" ? "image/jpeg" : "image/png";
  avatarData[memberName] = `data:${mimeType};base64,${fs.readFileSync(imagePath).toString("base64")}`;
}

const output = [
  "// Generated by scripts/build-share-avatar-data.mjs. Do not edit by hand.",
  `window.LOVELIVE_SHARE_AVATARS = Object.freeze(${JSON.stringify(avatarData)});`,
  ""
].join("\n");

fs.writeFileSync(path.join(distDirectory, "share-avatar-data.js"), output);
console.log(`Embedded ${Object.keys(avatarData).length} share-report avatars.`);
